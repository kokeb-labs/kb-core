"""Write configurator/offline.html: index.html with its stylesheet and scripts inlined.

Browsers refuse Subresource Integrity checks on file:// URLs, so index.html (served over https, every script
and the stylesheet pinned by an integrity hash) cannot run when opened from disk. offline.html carries the same
bytes inline and pins each inline block with a sha384 hash source in its Content Security Policy instead, which
browsers enforce on file:// too. Both pages run the same code. Usage: bundle_offline.py [--check]
"""

from __future__ import annotations

import base64
import hashlib
import re
import sys
from pathlib import Path

CONF = Path(__file__).resolve().parent.parent
SRC = CONF / "index.html"
OUT = CONF / "offline.html"


def h384(text: str) -> str:
    return "'sha384-" + base64.b64encode(hashlib.sha384(text.encode("utf-8")).digest()).decode() + "'"


def build() -> str:
    html = SRC.read_text()
    scripts: list[str] = []
    styles: list[str] = []

    def style(m: re.Match) -> str:
        body = (CONF / m.group(1)).read_text()
        styles.append(h384(body))
        return f"<style>{body}</style>"

    def script(m: re.Match) -> str:
        body = (CONF / m.group(1)).read_text()
        if re.search(r"</script|<!--", body, re.I):
            raise SystemExit(f"bundle_offline: {m.group(1)} contains a sequence that cannot be inlined")
        scripts.append(h384(body))
        return f"<script>{body}</script>"

    def module(m: re.Match) -> str:
        # The shared resolver is an ES module; a file:// page cannot import one, so its exports become a
        # classic script's object, and the boot module's two lines follow it.
        src = (CONF / "resolver.mjs").read_text()
        if re.search(r"^\s*import\b", src, re.M):
            raise SystemExit("bundle_offline: resolver.mjs imports another module; extend the bundler")
        names = re.findall(r"^export (?:const|function) ([A-Za-z0-9_]+)", src, re.M)
        body = re.sub(r"^export (const|function) ", r"\1 ", src, flags=re.M)
        body = ("(function () {\n" + body + "\nglobalThis.KB.engine = { " + ", ".join(names) + " };\n})();\n"
                "globalThis.KB.ui.refresh();\n")
        if re.search(r"</script|<!--", body, re.I):
            raise SystemExit("bundle_offline: resolver.mjs contains a sequence that cannot be inlined")
        scripts.append(h384(body))
        return f"<script>{body}</script>"

    html = re.sub(r'<link rel="modulepreload" href="[^"]+" integrity="[^"]+">\n', "", html)
    html = re.sub(r'<script type="module" src="js/boot.mjs" integrity="[^"]+"></script>', module, html)
    html = re.sub(r'<link rel="stylesheet" href="([^"]+)" integrity="[^"]+">', style, html)
    html = re.sub(r'<script src="([^"]+)" integrity="[^"]+"(?: defer)?></script>', script, html)
    html = re.sub(r'<p class="file-notice".*?</p>\n', "", html, flags=re.S)
    csp_old = re.search(r'content="(default-src[^"]+)"', html).group(1)
    csp = csp_old.replace("script-src 'self'", "script-src " + " ".join(scripts))
    csp = csp.replace("style-src 'self'", "style-src " + " ".join(styles))
    html = html.replace(csp_old, csp)
    banner = ("<!-- GENERATED by configurator/tools/bundle_offline.py from index.html: do not edit. The same page "
              "with every script and the stylesheet inline, for use from a file. -->\n")
    return html.replace("<!doctype html>\n", "<!doctype html>\n" + banner, 1)


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("bundle_offline: up to date" if ok else "bundle_offline: offline.html is stale; rerun the tool")
        return 0 if ok else 1
    OUT.write_text(text)
    print(f"bundle_offline: wrote {OUT.name} ({len(text.encode()) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
