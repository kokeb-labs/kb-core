"""Render configurator/data/vulnerabilities.json into the files the site is built from.

  collect.py --site configurator/data [--docs docs/assurance/vulnerabilities.md]
      write vulnerabilities.js (the same JSON as a script, so the page also works from a file) and the Markdown page
  collect.py --site configurator/data --docs PAGE --check
      fail when either is stale or the JSON is invalid; the page is judged as of the day of the scan, so the check
      never depends on the clock and never rescans

The page says plainly when the data is more than ten days older than the build (--today overrides the build date).
Schema: catalog/schemas/vulnerabilities.schema.json; the scan is tools/vuln/scan.py.
"""

from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import sys
import textwrap

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import scan  # noqa: E402

NAME = "vulnerabilities"


def render_js(doc: dict) -> str:
    text = json.dumps(doc, indent=1, sort_keys=True, ensure_ascii=False)
    return ("// SPDX-License-Identifier: MIT\n// Copyright (c) 2026 The kb-core authors\n"
            "// GENERATED by tools/vuln/collect.py --site: do not edit. data/vulnerabilities.json (kb-vulns/1), as a\n"
            "// script so the page also works from a file. Older than stale_after_days: the page must say so.\n"
            f"globalThis.KB_VULNERABILITIES = {text};\n")


def age_days(doc: dict, today: str) -> int:
    return (datetime.date.fromisoformat(today) - datetime.date.fromisoformat(doc["checked_at"])).days


def _wrap(text: str) -> list[str]:
    return textwrap.wrap(text, 118, break_long_words=False, break_on_hyphens=False)


def _cell(v) -> str:
    return str(v).replace("|", "\\|")


def render_docs(doc: dict, today: str) -> str:
    age = age_days(doc, today)
    t = doc["totals"]
    out = [
        "# Known vulnerabilities",
        "",
        "<!-- GENERATED by tools/vuln/collect.py --site configurator/data --docs docs/assurance/vulnerabilities.md: do",
        "not edit; the data is configurator/data/vulnerabilities.json (schema catalog/schemas/vulnerabilities.schema.json),",
        "written by tools/vuln/scan.py. -->",
        "",
    ]
    if age > doc["stale_after_days"]:
        out += ["> " + ln for ln in textwrap.wrap(
            f"**This data is {age} days old.** The scan ran on {doc['checked_at']}, more than {doc['stale_after_days']} days before this page was "
            "built. Treat the result as out of date: the scan may have failed, see the open issues of the "
            "repository.", 114)] + [""]
    out += _wrap(
        f"Checked on **{doc['checked_at']}** (UTC) against the [OSV](https://osv.dev) database, by `{doc['scanner']}`. "
        "The scan asks about the commit of each pinned component, so a release candidate and a moved tag are judged "
        "by the code that is pinned. A scan workflow repeats it, rebuilds this page and the configurator's data, "
        "and opens an issue when an advisory appears; it commits nothing. If the data is more than "
        f"{doc['stale_after_days']} days old the configurator and this page say so.") + [""]
    if t["advisories"] == 0:
        out += [f"**None known** for any of the {t['components']} pinned components.", ""]
    else:
        out += _wrap(f"**{t['open']} open, {t['reviewed']} reviewed** of {t['advisories']} "
                     f"advisor{'y' if t['advisories'] == 1 else 'ies'} for {t['with_advisories']} of the "
                     f"{t['components']} pinned components; **none known** for the others.") + [""]
    out += _wrap("An advisory means the database lists the pinned commit as affected. It is not a verdict on whether "
                 "kb-core or a product built from it is exposed: read the advisory, then decide, and record the "
                 "decision in the [SOUP list](soup.md).")
    if t["reviewed"]:
        out += [""] + _wrap(
            "A reviewed advisory is one on the reviewed list, `tools/vuln/reviewed.json` "
            "(`kb-vex/1`): its primary source, the upstream advisory, names the exact pinned version as patched, and "
            "the entry holds the reason, the source and the date of the review. It stays in the list, marked "
            "*fixed in the pinned version*, and does not count as open. An entry applies only while the scanned "
            "version equals the one it was reviewed for; if the pin moves, the advisory is open again. See "
            "[Known data issues](../configurator.md#known-data-issues).")
    out += ["", "## Components", "",
            "| Component | Version | Commit | Status | Open | Reviewed |", "| --- | --- | --- | --- | --- | --- |"]
    for c in doc["components"]:
        out.append(f"| `{_cell(c['name'])}` | `{_cell(c['version'])}` | `{c['commit'][:12]}` | {c['status']} | "
                   f"{c['open']} | {c['reviewed']} |")
    out.append("")
    for c in doc["components"]:
        if not c["count"]:
            continue
        out += [f"## {c['name']} {c['version']}", "", f"Package URL `{c['purl']}`.", ""]
        opened = [a for a in c["advisories"] if "review" not in a]
        done = [a for a in c["advisories"] if "review" in a]
        if opened:
            out += ["### Open", "", "| Advisory | Severity | Summary |", "| --- | --- | --- |"]
            for a in opened:
                out.append(f"| [{a['id']}]({a['url']}) | {a['severity']} | {_cell(a['summary'])} |")
            out.append("")
        if done:
            out += ["### Reviewed: fixed in the pinned version", ""]
            for a in done:
                r = a["review"]
                head = f"- [{a['id']}]({a['url']}) ({a['severity']}), reviewed {r['reviewed']}. "
                out += textwrap.wrap(head + r["reason"] + f" Source: <{r['source']}>", 118, subsequent_indent="  ",
                                     break_long_words=False, break_on_hyphens=False)
            out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--site", type=pathlib.Path, required=True, help="the configurator's data folder")
    ap.add_argument("--docs", type=pathlib.Path, help="also write (or check) this Markdown page")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--today", help="the build date for the stale warning (default: today, UTC)")
    args = ap.parse_args(argv)
    src = args.site / f"{NAME}.json"
    try:
        doc = json.loads(src.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        print(f"collect: cannot read {src}: {exc}")
        return 2
    errs = scan.problems(doc)
    if errs:
        for e in errs:
            print(f"collect: {src}: {e}")
        return 1
    if args.check:
        today = doc["checked_at"]  # a pure function of the file
    else:
        today = args.today or datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")
    outputs = [(args.site / f"{NAME}.js", render_js(doc))]
    if args.docs:
        outputs.append((args.docs, render_docs(doc, today)))
    if args.check:
        stale = [t for t, text in outputs if not t.exists() or t.read_text(encoding="utf-8") != text]
        for t in stale:
            print(f"collect: {t} is stale; run tools/vuln/collect.py --site {args.site}"
                  + (f" --docs {args.docs}" if args.docs else ""))
        if not stale:
            print("collect: vulnerability outputs up to date")
        return 1 if stale else 0
    for t, text in outputs:
        t.write_text(text, encoding="utf-8")
        print(f"collect: wrote {t} ({len(text.encode()) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
