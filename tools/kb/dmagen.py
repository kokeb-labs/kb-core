def _report_data(b, result):
    per_region = {}
    for x in result["buffers"]:
        e = per_region.setdefault(x["region"], {"region": x["region"], "buffers": 0, "bytes": 0, "padded_bytes": 0})
        e["buffers"] += 1
        e["bytes"] += x["bytes"]
        e["padded_bytes"] += x["capacity"]
    sizes = {r["name"]: r["size"] for r in result["regions"]}
    for name, e in per_region.items():
        e["region_size"] = sizes.get(name)
    return {
        "board": b["board"],
        "buses": [{"name": x["name"], "kind": x["kind"], "model": x["model"], "mode": x["mode"],
                   "streams": x["streams"], "staging_bytes": x["staging_bytes"], "limits": x["limits"],
                   "devices": x["devices"]} for x in result["buses"]],
        "buffers": result["buffers"],
        "regions": [per_region[k] for k in sorted(per_region)],
        "gdma_pairs": result["gdma_pairs"],
        "streams": [{k: v for k, v in s.items() if k in (
            "name", "engine", "unit", "request", "request_line", "mux_channel", "driver", "host", "priority",
            "irq_priority", "notify", "mode", "buffer", "shape", "frame_bytes", "frames", "iram_safe")}
            for s in result["streams"]],
        "findings": result["findings"],
    }


def _report_json(b, result):
    return canonical_json(_report_data(b, result))


def _cell(v):
    return "-" if v is None else str(v)


def _report_md(b, result):
    d = _report_data(b, result)
    out = [f"<!-- generated by kb board gen from {b['board']} — do not edit -->", f"# DMA report: {b['board']}", "",
           "## Buses", ""]
    if d["buses"]:
        out += ["| Bus | Kind | Mode | Streams | Staging bytes | Largest frame |", "| --- | --- | --- | --- | --- | --- |"]
        for x in d["buses"]:
            lim = x["limits"]
            carry = lim["max_frame_dma"] if lim["dma"] else lim["max_frame_no_dma"]
            out.append(f"| {x['name']} | {x['kind']} | {x['mode']} | {', '.join(x['streams']) or '-'} | "
                       f"{_cell(x['staging_bytes'])} | {'unbounded' if carry is None else carry} |")
    else:
        out.append("No bus is declared.")
    out += ["", "## Buffers per region", ""]
    if d["regions"]:
        out += ["| Region | Buffers | Bytes | Padded bytes | Region size |", "| --- | --- | --- | --- | --- |"]
        for r in d["regions"]:
            out.append(f"| {r['region']} | {r['buffers']} | {r['bytes']} | {r['padded_bytes']} | "
                       f"{_cell(r['region_size'])} |")
        out += ["", "| Buffer | Region | Bytes | Padded bytes | Section |", "| --- | --- | --- | --- | --- |"]
        for x in d["buffers"]:
            out.append(f"| {x['name']} | {x['region']} | {x['bytes']} | {x['capacity']} | {x['section']} |")
    else:
        out.append("No buffer is declared.")
    out += ["", "## Streams", ""]
    if b["mcu"]["family"] == "stm32":
        out += ["| Stream | Engine | Unit | Request | Line | IRQ priority | Notify | Mode | Buffer |",
                "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
        for s in d["streams"]:
            out.append(f"| {s['name']} | {s['engine']} | {s['unit']} | {s['request']} | {s['request_line']} | "
                       f"{s['irq_priority']} | {s['notify']} | {s['mode']} | {s['buffer']} |")
    else:
        out += ["| Stream | Driver | Host | Frame bytes | Frames | IRAM safe |", "| --- | --- | --- | --- | --- | --- |"]
        for s in d["streams"]:
            out.append(f"| {s['name']} | {s['driver']} | {_cell(s.get('host'))} | {_cell(s.get('frame_bytes'))} | "
                       f"{_cell(s.get('frames'))} | {'yes' if s.get('iram_safe') else 'no'} |")
        out += ["", f"GDMA pairs: {d['gdma_pairs']['used']} of {d['gdma_pairs']['budget']} used."]
    out += ["", "## Findings", ""]
    if d["findings"]:
        out += ["| Rule | Severity | Code | Subject | Message |", "| --- | --- | --- | --- | --- |"]
        for f in d["findings"]:
            out.append(f"| {f['rule']} | {f['severity']} | {f['code']} | {f['subject']} | {f['message']} |")
    else:
        out.append("None.")
    out.append("")
    return "\n".join(out)
