def _mpu(b, result):
    rows = result["mpu"]
    out = [_banner(b), "#ifndef BOARD_MPU_HPP", "#define BOARD_MPU_HPP", "", "#include <array>", "#include <cstddef>",
           "#include <cstdint>", "", "namespace board::mpu {", "",
           "/// One MPU region as data: the board's start-up programs it, the port reads it back (RBAR/RASR).",
           "struct Entry {", "  std::uint8_t number;", "  std::uint32_t base;", "  std::uint32_t size;",
           "  std::uint8_t tex;", "  bool c;", "  bool b;", "  bool s;", "  bool xn;", "};", ""]
    if rows:
        out.append(f"inline constexpr std::array<Entry, {len(rows)}> kRegions{{{{")
        for m in rows:
            out.append(f"    {{{m['number']}U, 0x{m['base']:08X}U, {m['size']}U, {m['tex']}U, "
                       f"{'true' if m['c'] else 'false'}, {'true' if m['b'] else 'false'}, "
                       f"{'true' if m['s'] else 'false'}, {'true' if m['xn'] else 'false'}}},  // {m['region']}")
        out.append("}};")
    else:
        out.append("inline constexpr std::array<Entry, 0> kRegions{};")
    out += ["", "} // namespace board::mpu", "", "#endif // BOARD_MPU_HPP", ""]
    return "\n".join(out)


