# board_dma.cpp

def _source(b, result, family):
    out = [_banner(b), '#include "board_dma.hpp"', "", "namespace board::dma {", ""]
    if result["buffers"]:
        out += ["// The one generated deviation from \"no object in a named section\": each buffer below sits in the",
                "// output section of its region (kb_dma.ld), so it lands in the memory and the MPU window the board",
                "// declared. A buffer is valid all-zero, so the section is NOLOAD and zeroed by the start-up."]
    for x in result["buffers"]:
        out.append(f"KB_DMA_SECTION(\"{x['section']}\") kb::dma::Buffer<region::{boardmod.camel(x['region'])}, "
                   f"{_u(x['bytes'])}> {x['name']};")
    out += ["", "} // namespace board::dma", ""]
    return "\n".join(out)


