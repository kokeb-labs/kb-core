# kb_dma.ld

def _linker(b, result):
    prefix = b["linker"]["noload_list"]
    regions = {r["name"]: r for r in result["regions"]}
    mpu = {m["region"]: m for m in result["mpu"]}
    out = [_banner(b, "/*") + " */",
           "/* INCLUDE this file in the board's linker script, outside SECTIONS. */", "", "SECTIONS", "{"]
    secs = _sections(result)
    for name in secs:
        r = regions[name]
        out += [f"  .kb_dma.{name} {_hex(r['base'])[:-1]} (NOLOAD) : ALIGN({r['align']})", "  {",
                f"    {prefix}_{name}_start = .;", f"    KEEP(*(.kb_dma.{name}))", f"    . = ALIGN({r['align']});",
                f"    {prefix}_{name}_end = .;", "  }"]
    out += ["}", ""]
    for name in secs:
        r = regions[name]
        base, size = _hex(r["base"])[:-1], r["base"] + r["size"]
        out.append(f"ASSERT({prefix}_{name}_start == {base} && {prefix}_{name}_end <= 0x{size:08X}, "
                   f"\"kb_dma: section .kb_dma.{name} does not fit its region {name}\")")
        if name in mpu:
            m = mpu[name]
            out.append(f"ASSERT({prefix}_{name}_start == 0x{m['base']:08X} && {prefix}_{name}_end <= "
                       f"0x{m['base'] + m['size']:08X}, \"kb_dma: section .kb_dma.{name} is not inside its MPU "
                       f"region {m['number']}\")")
        for sec in b["linker"]["fixed_sections"]:
            out.append(f"ASSERT(0x{sec['base'] + sec['size']:08X} <= {prefix}_{name}_start || 0x{sec['base']:08X} >= "
                       f"{prefix}_{name}_end, \"kb_dma: section .kb_dma.{name} overlaps {sec['name']}\")")
    out.append("")
    return "\n".join(out)


