"""`generate(board, result) -> {file name: text}`."""

from . import board as boardmod
from .emit import canonical_json

HEADER = "board_dma.hpp"
SOURCE = "board_dma.cpp"
LINKER = "kb_dma.ld"
MPU = "board_mpu.hpp"
REPORT_MD = "board_dma_report.md"
REPORT_JSON = "board_dma_report.json"

_POLICY = {"Coherent": "Coherent", "NonCacheable": "NonCacheable", "Maintained": "Maintained"}
_PRIORITY = {"low": "Low", "medium": "Medium", "high": "High", "very_high": "VeryHigh"}
_NOTIFY = {"none": "None", "task": "Task"}
_IRQ = {"all": "All", "errors_only": "ErrorsOnly"}
_MODE = {"normal": "Normal", "circular": "Circular"}


class GenerateError(Exception):
    """The board did not check ok, or the result does not belong to it."""


def _banner(board, comment="//"):
    return f"{comment} generated by kb board gen from {board['board']} — do not edit"


def _u(n):
    return f"{n}U"


def _hex(n):
    return f"0x{n:08X}U"


def _master_const(name):
    return "k" + boardmod.camel(name)


def _masters_expr(names):
    if not names:
        return "kb::dma::MasterSet{0U}"
    return " | ".join(f"master::{_master_const(n)}" for n in names)


def generate(board, result):
    """The generated files of a board whose `check` result is ok: {file name: text}. `result` is what
    `dmacheck.check` returned (its `resolved` part carries the master numbers, regions, buffers, streams, buses and
    MPU table)."""
    b, issues = boardmod.normalise(board)
    if issues:
        raise GenerateError("the board is malformed: " + "; ".join(m for _, m in issues))
    if not result["ok"]:
        raise GenerateError("the board has errors: run kb image check first")
    family = b["mcu"]["family"]
    result = {**result["resolved"], "ok": result["ok"], "findings": result["findings"]}  # one flat view below
    files = {
        HEADER: _header(b, result, family, result["masters"]),
        SOURCE: _source(b, result, family),
        REPORT_MD: _report_md(b, result),
        REPORT_JSON: _report_json(b, result),
    }
    if family == "stm32":
        files[LINKER] = _linker(b, result)
        if result["cached_core"]:
            files[MPU] = _mpu(b, result)
    return files


# ----------------------------------------------------------------------------------------------------------------
# board_dma.hpp

def _region_tag(r, family):
    lines = [f"/// Region {r['name']}: " + (f"{_hex(r['base'])[:-1]} + {r['size']} bytes in {r['memory']}, "
                                           if r["base"] is not None and r["memory"] else "")
             + f"{r['policy']}" + (f", MPU region {r['mpu_region']}" if r["mpu_region"] is not None else "") + ".",
             f"struct {boardmod.camel(r['name'])} {{",
             f"  static constexpr kb::dma::CachePolicy kPolicy = kb::dma::CachePolicy::{_POLICY[r['policy']]};",
             f"  static constexpr std::size_t kLineBytes = {_u(r['line'])};",
             f"  static constexpr std::size_t kAlignBytes = {_u(r['align'])};",
             f"  static constexpr kb::dma::MasterSet kMasters = {_masters_expr(r['masters'])};"]
    if r["base"] is not None and r["size"] is not None:
        lines.append(f"  static constexpr std::uintptr_t kBase = {_hex(r['base'])};")
        lines.append(f"  static constexpr std::size_t kSize = {_u(r['size'])};")
    lines.append("};")
    lines.append(f"static_assert(kb::dma::Region<{boardmod.camel(r['name'])}>);")
    return lines


def _stream_tag(s, result, regions, buffers, family):
    lines = [f"/// Stream {s['name']}" + (f": {s['request']} on {s['engine']} {s['unit']}" if family == "stm32" else
                                         f": {s['driver']}" + (f" {s['host']}" if s.get('host') else "")) + "."]
    lines.append(f"struct {boardmod.camel(s['name'])} {{")
    if family == "stm32":
        lines += [
            "  static constexpr kb::dma::StreamAssignment kAssignment{",
            f"      {_u(s['engine_id'])}, {_u(s['unit'])}, {_u(s['request_line'])},",
            f"      kb::dma::ChannelPriority::{_PRIORITY[s['priority']]}, {_u(s['irq_priority'])},",
            f"      kb::dma::Notify::{_NOTIFY[s['notify']]}, kb::dma::IrqUse::{_IRQ[s['irq']]},",
            f"      kb::dma::ChannelMode::{_MODE[s['mode']]}}};",
            f"  static constexpr kb::dma::MasterSet kMaster = master::{_master_const(s['engine'])};",
        ]
        buf = buffers[s["buffer"]]
        lines.append(f"  using RegionType = region::{boardmod.camel(buf['region'])};")
        lines.append(f"  static constexpr std::size_t kBufferBytes = {_u(buf['bytes'])};")
    else:
        lines.append(f"  static constexpr bool kIramSafe = {'true' if s['iram_safe'] else 'false'};")
        if s.get("host"):
            lines.append(f"  static constexpr const char* kHost = \"{s['host']}\";")
        if s.get("frame_bytes"):
            lines.append(f"  static constexpr std::size_t kFrameBytes = {_u(s['frame_bytes'])};")
        if s.get("frames"):
            lines.append(f"  static constexpr std::size_t kFrames = {_u(s['frames'])};")
    if s.get("shape"):
        sh = s["shape"]
        lines.append(f"  static constexpr kb::dma::StreamShape kShape{{{_u(sh['frames'])}, {_u(sh['element_bytes'])}, "
                     f"{_u(sh['elements'])}}};")
    lines.append("};")
    return lines


def _bus_tag(bus):
    lim = bus["limits"]
    no_dma = "std::numeric_limits<std::size_t>::max()" if lim["max_frame_no_dma"] is None else _u(lim["max_frame_no_dma"])
    return [f"/// Bus {bus['name']} ({bus['kind']}, {bus['mode']}).",
            f"struct {boardmod.camel(bus['name'])} {{",
            "  static constexpr kb::dma::BusLimits kBus{",
            f"      {'true' if lim['dma'] else 'false'}, {_u(lim['max_frame_dma'])}, {no_dma}, "
            f"{_u(lim['rx_length_multiple'])}, {_u(lim['align_bytes'])}}};",
            "};"]


def _header(b, result, family, masters):
    regions = {r["name"]: r for r in result["regions"]}
    buffers = {x["name"]: x for x in result["buffers"]}
    streams = {s["name"]: s for s in result["streams"]}
    out = [_banner(b), "#ifndef BOARD_DMA_HPP", "#define BOARD_DMA_HPP", "",
           "#include <cstddef>", "#include <cstdint>", "#include <limits>", "",
           '#include "kb/dma/assignment.hpp"', '#include "kb/dma/buffer.hpp"', '#include "kb/dma/region.hpp"', "",
           "// KB_DMA_SECTION(name) puts a buffer in the output section of its region (kb_dma.ld). It is empty where the "
           "target has no such section.", "#ifndef KB_DMA_SECTION"]
    if family == "stm32":
        out += ["#if defined(__ELF__)", "#define KB_DMA_SECTION(name) [[gnu::section(name)]]", "#else",
                "#define KB_DMA_SECTION(name)", "#endif"]
    else:
        out += ["#define KB_DMA_SECTION(name)"]
    out += ["#endif", "", "namespace board::dma {", ""]
    names = sorted(masters, key=lambda n: masters[n])
    out.append("/// The DMA masters of this part, numbered as the port numbers them.")
    out.append("namespace master {")
    for n in names:
        out.append(f"inline constexpr kb::dma::MasterSet {_master_const(n)} = kb::dma::MasterBit({_u(masters[n])});")
    out += ["} // namespace master", ""]
    out.append("namespace region {")
    for name in sorted(regions):
        out += _region_tag(regions[name], family) + [""]
    out += ["} // namespace region", ""]
    if b["rtos"]:
        out += ["/// What the RTOS allows interrupts to do.", "struct Rtos {",
                f"  static constexpr kb::dma::InterruptLimits kLimits{{{_u(b['rtos']['max_syscall_priority'])}, "
                f"{_u(b['rtos']['priority_bits'])}}};", "};", ""]
    if streams:
        out.append("namespace stream {")
        for name in sorted(streams):
            out += _stream_tag(streams[name], result, regions, buffers, family) + [""]
        out += ["} // namespace stream", ""]
    if result["buses"]:
        out.append("namespace bus {")
        for bus in result["buses"]:
            out += _bus_tag(bus) + [""]
        out += ["} // namespace bus", ""]
    if buffers:
        out.append("/// The DMA buffers; defined in board_dma.cpp, in the section of their region.")
        for name in sorted(buffers):
            x = buffers[name]
            out.append(f"KB_DMA_SECTION(\"{x['section']}\") extern kb::dma::Buffer<region::"
                       f"{boardmod.camel(x['region'])}, {_u(x['bytes'])}> {name};")
        out.append("")
    out += _checks(b, result, family, regions, buffers, streams)
    if family == "stm32" and buffers:
        out += _noload(b, result)
    out += ["} // namespace board::dma", "", "#endif // BOARD_DMA_HPP", ""]
    return "\n".join(out)


def _checks(b, result, family, regions, buffers, streams):
    """The compile-time checks: a board file that drifted from the checker fails to build."""
    calls = []
    asserts = []
    for name in sorted(streams):
        s = streams[name]
        tag = f"stream::{boardmod.camel(name)}"
        if family == "stm32":
            if b["rtos"]:
                calls.append(f"kb::dma::RequireInterruptTier<{tag}, Rtos>()")
            buf = buffers[s["buffer"]]
            reg = f"region::{boardmod.camel(buf['region'])}"
            calls.append(f"kb::dma::RequireReachable<{tag}::kMaster, {reg}>()")
            if s.get("shape"):
                asserts.append(f"static_assert({tag}::kShape.frames * {tag}::kShape.FrameBytes() <= "
                               f"{_u(buf['bytes'])}, \"stream {name}: the ring does not fit its buffer\");")
    for name in sorted(buffers):
        x = buffers[name]
        calls.append(f"kb::dma::RequireWholeUnits<{_u(x['capacity'])}, region::{boardmod.camel(x['region'])}>()")
    groups = {}
    for name in sorted(streams):
        per = streams[name].get("peripheral")
        if per:
            groups.setdefault(per, []).append(name)
    for per in sorted(groups):
        first, *rest = groups[per]
        for other in rest:
            calls.append(f"kb::dma::RequireSamePriority<stream::{boardmod.camel(first)}, "
                         f"stream::{boardmod.camel(other)}>()")
    for bus in result["buses"]:
        for dev in bus["devices"]:
            if dev["max_frame_bytes"] is not None:
                calls.append(f"kb::dma::RequireBusCarries<bus::{boardmod.camel(bus['name'])}, "
                             f"{_u(dev['max_frame_bytes'])}>()")
    out = ["/// Compile-time checks (ADR-0033): each call is a `static_assert` of kb/dma, so a board file that",
           "/// drifted from `kb image check` does not build."]
    if calls:
        out.append("inline constexpr bool kChecksPass = (")
        out += [f"    {c}," for c in calls] + ["    true);"]
    else:
        out.append("inline constexpr bool kChecksPass = true;")
    out += asserts + [""]
    return out


def _noload(b, result):
    prefix = b["linker"]["noload_list"]
    secs = _sections(result)
    out = ["/// The linker symbols of the generated NOLOAD sections (kb_dma.ld), for the board's start-up.",
           "extern \"C\" {"]
    for r in secs:
        out.append(f"extern std::byte {prefix}_{r}_start[];")
        out.append(f"extern std::byte {prefix}_{r}_end[];")
    out += ["}", "", "/// One generated section as [begin, end).", "struct NoloadRange {", "  std::byte* begin;",
            "  std::byte* end;", "};", f"inline constexpr std::size_t kNoloadCount = {_u(len(secs))};", "",
            "/// Fills `out` with every generated DMA section: zero them with the board's other NOLOAD sections",
            "/// before constructors run, and include them in the ECC scrub (a buffer is valid all-zero).",
            "inline void NoloadRanges(NoloadRange (&out)[kNoloadCount]) noexcept {"]
    for i, r in enumerate(secs):
        out.append(f"  out[{i}] = NoloadRange{{{prefix}_{r}_start, {prefix}_{r}_end}};")
    out += ["}", ""]
    return out


def _sections(result):
    """The regions that hold at least one buffer, in name order."""
    used = {x["region"] for x in result["buffers"]}
    return sorted(used)


